// The app builds its DOM once at startup (vanilla JS, no reactive
// framework), so there's no live re-render when the locale changes —
// setLocale() persists the choice and reloads the page, and every t() call
// made during the next startup picks it up. That's a deliberate,
// appropriately-sized choice for this architecture: a full reactive i18n
// layer would mean threading update callbacks through every dialog/toolbar
// element for a page that already reloads instantly.
//
// t(key) falls back to the English string, then to the key itself, so a
// missing translation is visible/debuggable rather than silently blank.

