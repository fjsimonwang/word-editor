export function detectLocale() {
  try {
    const saved = localStorage.getItem(LOCALE_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch {}
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("zh")) return "zh";
  return "en";
}

export function getLocale() {
  if (!currentLocale) currentLocale = detectLocale();
  return currentLocale;
}

export function setLocale(loc) {
  if (!STRINGS[loc]) return;
  try { localStorage.setItem(LOCALE_KEY, loc); } catch {}
  currentLocale = loc;
  location.reload();
}

export function t(key, vars) {
  const loc = getLocale();
  let s = (STRINGS[loc] && STRINGS[loc][key]) ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

// Translates the static HTML shell (menus, panel headings, etc.) — anything
// built dynamically in editor.js/main.js already calls t() directly at
// creation time and doesn't need this. Elements opt in via data-i18n (sets
// textContent), data-i18n-title (title attribute), and data-i18n-placeholder
// (placeholder attribute).
export function applyI18n(root = document) {
  document.documentElement.lang = getLocale() === "zh" ? "zh-CN" : "en";
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.getAttribute("data-i18n"));
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.getAttribute("data-i18n-title"));
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  // data-i18n-html: like data-i18n but sets innerHTML instead of textContent,
  // for the handful of strings that embed real markup (e.g. <code>, <b>).
  // Only ever fed from STRINGS below (developer-authored, not user input).
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.getAttribute("data-i18n-html"));
}
